const langCycle = ['en', 'am', 'ar'];
const langLabels = { en: '🇺🇸 EN', am: '🇪🇹 AM', ar: '🇸🇦 AR' };

function getCurrentLang() {
    return localStorage.getItem('lang') || 'en';
}

function t(key) {
    const lang = getCurrentLang();
    return (translations[lang] && translations[lang][key])
        || (translations['en'] && translations['en'][key])
        || key;
}

function applyTranslations(lang) {
    const tr = translations[lang] || translations['en'];
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (tr[key] !== undefined) {
            // Don't override submit button while it shows a status message
            if (el.id === 'submit-btn' &&
                (el.classList.contains('submitted') || el.classList.contains('submit-error'))) {
                return;
            }
            el.textContent = tr[key];
        }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (tr[key] !== undefined) el.innerHTML = tr[key];
    });

    const langSelect = document.getElementById('lang-select');
    if (langSelect) langSelect.value = lang;

    // Translate guests select options
    const guestsSelect = document.getElementById('guests');
    if (guestsSelect) {
        const keys = ['room_guests_placeholder', 'room_guest1', 'room_guest2', 'room_guest3', 'room_guest4'];
        guestsSelect.querySelectorAll('option').forEach((opt, i) => {
            if (keys[i] && tr[keys[i]]) opt.textContent = tr[keys[i]];
        });
    }
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getCurrentLang());

    const langSelect = document.getElementById('lang-select');
    if (langSelect) {
        langSelect.addEventListener('change', () => {
            localStorage.setItem('lang', langSelect.value);
            applyTranslations(langSelect.value);
        });
    }

    // Hamburger menu toggle (shared across all pages)
    const hamburger = document.getElementById('hamburger');
    const navLinks = document.getElementById('nav-links');
    const navClose = document.getElementById('nav-close');

    if (hamburger && navLinks) {
        hamburger.addEventListener('click', () => {
            navLinks.classList.toggle('open');
        });
    }
    if (navClose && navLinks) {
        navClose.addEventListener('click', () => {
            navLinks.classList.remove('open');
        });
    }
});
