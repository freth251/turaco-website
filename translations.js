const SUPPORTED_LANGS = ['en', 'am', 'ar'];

function getCurrentLang() {
    try {
        const stored = localStorage.getItem('lang');
        if (stored && SUPPORTED_LANGS.indexOf(stored) !== -1) return stored;
    } catch (e) { /* storage blocked */ }
    return 'en';
}

function setCurrentLang(lang) {
    try { localStorage.setItem('lang', lang); } catch (e) { /* storage blocked */ }
}

function t(key) {
    const lang = getCurrentLang();
    return (translations[lang] && translations[lang][key])
        || (translations['en'] && translations['en'][key])
        || key;
}

function applyTranslations(lang) {
    const tr = translations[lang] || translations['en'];
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (tr[key] === undefined) return;
        // Don't clobber the submit button while it is showing a status message.
        if (el.id === 'submit-btn' &&
            (el.classList.contains('is-success') || el.classList.contains('is-error'))) {
            return;
        }
        el.textContent = tr[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (tr[key] !== undefined) el.innerHTML = tr[key];
    });

    // Icon-only controls carry their label in aria-label instead of text.
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (tr[key] !== undefined) el.setAttribute('aria-label', tr[key]);
    });

    document.querySelectorAll('.lang-pill').forEach(pill => {
        pill.setAttribute('aria-pressed', String(pill.dataset.lang === lang));
        var name = tr['lang_' + pill.dataset.lang];
        if (name) pill.setAttribute('aria-label', name);
    });

    var trigger = document.getElementById('lang-current');
    if (trigger) {
        var active = document.querySelector('.lang-pill[data-lang="' + lang + '"]');
        var label = active ? active.textContent : lang.toUpperCase();
        trigger.textContent = label;
        // The accessible name must contain the visible text (WCAG 2.5.3).
        trigger.setAttribute('aria-label', label + ' – ' + (tr.lang_menu || 'Change language'));
    }

    // Page-level metadata is part of the translation too.
    if (tr.site_title && !document.body.dataset.pageTitleKey) {
        document.title = tr.site_title;
    }
    var pageKey = document.body.dataset.pageTitleKey;
    if (pageKey && tr[pageKey]) document.title = tr[pageKey];

    var desc = document.querySelector('meta[name="description"]');
    var descKey = document.body.dataset.pageDescKey || 'site_description';
    if (desc && tr[descKey]) desc.setAttribute('content', tr[descKey]);

    // Let page scripts re-render anything that holds state (e.g. the submit button).
    document.dispatchEvent(new CustomEvent('turaco:langchange', { detail: { lang: lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getCurrentLang());

    const langPanel = document.getElementById('lang-pills');
    const langTrigger = document.getElementById('lang-current');

    function closeLangPanel() {
        if (!langPanel) return;
        langPanel.classList.remove('is-open');
        if (langTrigger) langTrigger.setAttribute('aria-expanded', 'false');
    }

    // The compact header control opens the three-language panel on small screens.
    if (langTrigger && langPanel) {
        langTrigger.addEventListener('click', e => {
            e.stopPropagation();
            const open = langPanel.classList.toggle('is-open');
            langTrigger.setAttribute('aria-expanded', String(open));
            if (open) {
                const first = langPanel.querySelector('.lang-pill');
                if (first) first.focus();
            }
        });
        document.addEventListener('click', e => {
            if (!langPanel.contains(e.target) && e.target !== langTrigger) closeLangPanel();
        });
    }

    document.querySelectorAll('.lang-pill').forEach(pill => {
        pill.addEventListener('click', () => {
            const lang = pill.dataset.lang;
            if (!lang || SUPPORTED_LANGS.indexOf(lang) === -1) return;
            setCurrentLang(lang);
            applyTranslations(lang);
            closeLangPanel();
        });
    });

    // Mobile navigation panel (shared across all pages).
    const navToggle = document.getElementById('nav-toggle');
    const nav = document.getElementById('site-nav');
    const navClose = document.getElementById('nav-close');

    const FOCUSABLE = 'a[href], button:not([disabled]), input, select, textarea';

    function openNav() {
        if (!nav) return;
        nav.classList.add('is-open');
        document.documentElement.classList.add('nav-open');
        if (navToggle) navToggle.setAttribute('aria-expanded', 'true');
        const first = nav.querySelector(FOCUSABLE);
        if (first) first.focus();
    }

    function closeNav() {
        if (!nav) return;
        nav.classList.remove('is-open');
        document.documentElement.classList.remove('nav-open');
        if (navToggle) {
            navToggle.setAttribute('aria-expanded', 'false');
            navToggle.focus();
        }
    }

    if (navToggle && nav) {
        navToggle.addEventListener('click', () => {
            if (nav.classList.contains('is-open')) closeNav(); else openNav();
        });
    }
    if (navClose) navClose.addEventListener('click', closeNav);
    if (nav) {
        nav.querySelectorAll('a').forEach(a => a.addEventListener('click', closeNav));
    }

    document.addEventListener('keydown', e => {
        if (e.key === 'Escape') {
            if (nav && nav.classList.contains('is-open')) closeNav();
            closeLangPanel();
            return;
        }
        // Keep keyboard focus inside the open menu.
        if (e.key === 'Tab' && nav && nav.classList.contains('is-open')) {
            const items = Array.from(nav.querySelectorAll(FOCUSABLE))
                .filter(el => el.offsetParent !== null);
            if (!items.length) return;
            const first = items[0];
            const last = items[items.length - 1];
            if (e.shiftKey && document.activeElement === first) {
                e.preventDefault();
                last.focus();
            } else if (!e.shiftKey && document.activeElement === last) {
                e.preventDefault();
                first.focus();
            }
        }
    });
});
